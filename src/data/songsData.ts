export interface Song {
  id: string; // generated client/server side
  banda: string;
  anio: number;
  disco: string;
  tema: string;
}

export function getParsedSongs(): Song[] {
  const lines = rawSongsCSV.trim().split("\n");
  const headers = lines[0].split(";"); // Banda;Año;Disco;Tema
  const songs: Song[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    const parts = line.split(";");
    if (parts.length >= 4) {
      const banda = parts[0];
      // Some lines might miss year or have typos, e.g. "Solista; Demasiado ego"
      let anioStr = parts[1]?.trim() || "";
      let discoIndex = 2;
      let temaIndex = 3;
      
      // Fix cases where a column is offset (e.g., "Solista; Demasiado ego;...")
      let anio = 1999; // Default for that missing 1999 Demasiado ego line representatively
      if (isNaN(Number(anioStr))) {
        anio = 1999;
        discoIndex = 1;
        temaIndex = 2;
      } else {
        anio = parseInt(anioStr, 10);
      }

      const disco = parts[discoIndex]?.trim() || "";
      const tema = parts[temaIndex]?.trim() || "";

      // Generate a stable safe id
      const safeId = `${banda}-${anio}-${disco}-${tema}`.replace(/[^a-zA-Z0-9]/g, "-").toLowerCase();

      songs.push({
        id: safeId,
        banda,
        anio,
        disco,
        tema
      });
    }
  }
  return songs;
}
